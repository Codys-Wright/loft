// Bang is one entry of the generated list (unduck's fields, url uses %TERM%).
type Bang struct {
	T  string `json:"t"`
	S  string `json:"s"`
	D  string `json:"d"`
	C  string `json:"c"`
	SC string `json:"sc"`
	U  string `json:"u"`
	R  int    `json:"r"`
}

type Quicklink struct {
	ID      string `json:"id,omitempty"`
	Keyword string `json:"keyword"`
	Name    string `json:"name,omitempty"`
	Bang    string `json:"bang,omitempty"`
	URL     string `json:"url,omitempty"`
	Icon    string `json:"icon,omitempty"`
}

type Settings struct {
	DefaultEngine string      `json:"defaultEngine"`
	Favorites     []string    `json:"favorites"`
	Quicklinks    []Quicklink `json:"quicklinks"`
}

// engine is anything that can be searched: a bang or a quicklink.
type engine struct {
	key      string // trigger / keyword (lower case)
	name     string
	url      string // with %TERM%, or a plain URL
	domain   string
	category string
	icon     string // explicit icon (quicklinks)
	rank     int
	quick    bool // a quicklink
	fav      int  // favorites position + 1, 0 = not a favorite

	lname, ldomain, lcat string
}

func (e *engine) template() bool { return strings.Contains(e.url, "%TERM%") }

var (
	mu       sync.RWMutex
	bangs    []*engine          // by rank, most used first
	byKey    map[string]*engine // bangs by trigger
	settings Settings
	quick    []*engine          // quicklinks, in order
	quickKey map[string]*engine // quicklinks by keyword (they win over bangs)
	setMTime time.Time
	setSize  int64
)

