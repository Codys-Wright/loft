func cleanDomain(d, u string) string {
	if !strings.Contains(d, ".") {
		if p, err := url.Parse(strings.ReplaceAll(u, "%TERM%", "x")); err == nil && p.Host != "" {
			d = p.Host
		}
	}
	return strings.TrimPrefix(strings.ToLower(d), "www.")
}

func asURL(s string) string {
	link := s
	if !strings.HasPrefix(link, "https://") && !strings.HasPrefix(link, "http://") {
		link = "https://" + link
	}
	u, err := url.ParseRequestURI(link)
	if err != nil || u.Host == "" {
		return ""
	}
	host := u.Hostname()
	if host != "localhost" && (!strings.Contains(host, ".") || strings.HasSuffix(host, ".") || strings.HasPrefix(host, ".")) {
		return ""
	}
	// "1.5" is a number, not a site.
	if strings.Trim(host, "0123456789.") == "" && strings.Count(host, ".") != 3 {
		return ""
	}
	return link
}

// favicons: icons.duckduckgo.com/ip3/<domain>.ico → <cache>/loft/favicons/<domain>.png,
// fetched in the background for rows being shown; the row updates when it lands.
var favicons = &faviconCache{inflight: map[string]bool{}, missing: map[string]bool{}}

type faviconCache struct {
	mu       sync.Mutex
	inflight map[string]bool
	missing  map[string]bool
	slots    chan struct{}
}

func (f *faviconCache) dir() string {
	d, _ := os.UserCacheDir()
	return filepath.Join(d, "loft", "favicons")
}

func safeDomain(d string) bool {
	return d != "" && !strings.ContainsAny(d, "/\\ ") && !strings.HasPrefix(d, ".")
}

func (f *faviconCache) path(domain string) string {
	if !config.Favicons || !safeDomain(domain) {
		return ""
	}
	p := filepath.Join(f.dir(), domain+".png")
	if _, err := os.Stat(p); err == nil {
		return p
	}
	return ""
}

func (f *faviconCache) want(conn net.Conn, format uint8, query string, it *pb.QueryResponse_Item) {
	domain := it.Subtext
	if i := strings.Index(domain, "  ·  "); i >= 0 {
		// subtext is "badge · domain · kind"; the domain is the part with a dot.
		domain = ""
		for _, p := range strings.Split(it.Subtext, "  ·  ") {
			if strings.Contains(p, ".") && !strings.Contains(p, " ") {
				domain = p
				break
			}
		}
	}
	if !safeDomain(domain) || !strings.Contains(domain, ".") {
		return
	}

	f.mu.Lock()
	if f.slots == nil {
		f.slots = make(chan struct{}, 4)
		_ = os.MkdirAll(f.dir(), 0o755)
	}
	if f.inflight[domain] || f.missing[domain] {
		f.mu.Unlock()
		return
	}
	if _, err := os.Stat(filepath.Join(f.dir(), domain+".none")); err == nil {
		f.missing[domain] = true
		f.mu.Unlock()
		return
	}
	f.inflight[domain] = true
	f.mu.Unlock()

	item := proto.Clone(it).(*pb.QueryResponse_Item) // sent as the update
	go func() {
		f.slots <- struct{}{}
		ok := fetchFavicon(domain, f.dir())
		<-f.slots

		f.mu.Lock()
		delete(f.inflight, domain)
		if !ok {
			f.missing[domain] = true
		}
		f.mu.Unlock()

		if ok && conn != nil {
			item.Icon = filepath.Join(f.dir(), domain+".png")
			handlers.UpdateItem(format, query, conn, item)
		}
	}()
}

var httpClient = &http.Client{Timeout: 6 * time.Second}

func fetchFavicon(domain, dir string) bool {
	out := filepath.Join(dir, domain+".png")
	fail := func() bool {
		_ = os.WriteFile(filepath.Join(dir, domain+".none"), nil, 0o644)
		return false
	}

	resp, err := httpClient.Get("https://icons.duckduckgo.com/ip3/" + url.PathEscape(domain) + ".ico")
	if err != nil {
		return false // offline: try again next time
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fail()
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		return false
	}

	pngData := toPNG(data)
	if pngData == nil {
		return fail()
	}
	tmp := out + ".tmp"
	if os.WriteFile(tmp, pngData, 0o644) != nil {
		return false
	}
	return os.Rename(tmp, out) == nil
}

var pngMagic = []byte("\x89PNG\r\n\x1a\n")

// toPNG: a PNG as is, or the largest image of an ICO (PNG or 32-bit BMP).
func toPNG(b []byte) []byte {
	if bytes.HasPrefix(b, pngMagic) {
		return b
	}
	if len(b) < 6 || binary.LittleEndian.Uint16(b[0:]) != 0 || binary.LittleEndian.Uint16(b[2:]) != 1 {
		return nil
	}
	n := int(binary.LittleEndian.Uint16(b[4:]))
	bestSize, bestOff, bestLen := -1, 0, 0
	for i := 0; i < n; i++ {
		o := 6 + i*16
		if o+16 > len(b) {
			return nil
		}
		w := int(b[o])
		if w == 0 {
			w = 256
		}
		size := int(binary.LittleEndian.Uint32(b[o+8:]))
		off := int(binary.LittleEndian.Uint32(b[o+12:]))
		if off+size > len(b) || size <= 0 {
			continue
		}
		if w > bestSize {
			bestSize, bestOff, bestLen = w, off, size
		}
	}
	if bestSize < 0 {
		return nil
	}
	img := b[bestOff : bestOff+bestLen]
	if bytes.HasPrefix(img, pngMagic) {
		return img
	}
	return bmpToPNG(img)
}

// bmpToPNG decodes an ICO's DIB (32-bit BGRA, bottom-up, height doubled).
func bmpToPNG(d []byte) []byte {
	if len(d) < 40 {
		return nil
	}
	hdr := int(binary.LittleEndian.Uint32(d[0:]))
	w := int(int32(binary.LittleEndian.Uint32(d[4:])))
	h := int(int32(binary.LittleEndian.Uint32(d[8:]))) / 2
	bpp := int(binary.LittleEndian.Uint16(d[14:]))
	if bpp != 32 || w <= 0 || h <= 0 || w > 512 || h > 512 || hdr+w*h*4 > len(d) {
		return nil
	}
	img := image.NewNRGBA(image.Rect(0, 0, w, h))
	px := d[hdr:]
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			i := ((h-1-y)*w + x) * 4
			img.SetNRGBA(x, y, color.NRGBA{R: px[i+2], G: px[i+1], B: px[i], A: px[i+3]})
		}
	}
	var buf bytes.Buffer
	if png.Encode(&buf, img) != nil {
		return nil
	}
	return buf.Bytes()
}
