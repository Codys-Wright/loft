func loadBangs() {
	start := time.Now()
	list := []Bang{}

	if config.Data != "" {
		b, err := os.ReadFile(config.Data)
		if err != nil {
			slog.Error(Name, "data", err)
		} else if err := json.Unmarshal(b, &list); err != nil {
			slog.Error(Name, "data", err)
		}
	}

	bs := make([]*engine, 0, len(list))
	keys := make(map[string]*engine, len(list))

	for _, b := range list {
		k := strings.ToLower(b.T)
		if k == "" || b.U == "" {
			continue
		}
		if _, dup := keys[k]; dup {
			continue
		}
		e := &engine{key: k, name: b.S, url: b.U, domain: cleanDomain(b.D, b.U), category: b.C, rank: b.R}
		if e.name == "" {
			e.name = b.T
		}
		e.lname, e.ldomain, e.lcat = strings.ToLower(e.name), strings.ToLower(e.domain), strings.ToLower(b.C+" "+b.SC)
		bs = append(bs, e)
		keys[k] = e
	}

	slices.SortStableFunc(bs, func(a, b *engine) int { return b.rank - a.rank })

	mu.Lock()
	bangs, byKey = bs, keys
	mu.Unlock()

	slog.Info(Name, "bangs", len(bs), "time", time.Since(start))
}

// reloadSettings re-reads spotlight.json when it changed (a stat per query).
func reloadSettings(force bool) {
	path := config.Settings
	st, err := os.Stat(path)

	if err != nil {
		if !force && setSize == -1 {
			return
		}
		// Not written yet: the seed.
		var s Settings
		if config.Defaults != "" {
			if b, err := os.ReadFile(config.Defaults); err == nil {
				_ = json.Unmarshal(b, &s)
			}
		}
		applySettings(s)
		setSize = -1
		return
	}

	if !force && st.ModTime().Equal(setMTime) && st.Size() == setSize {
		return
	}
	setMTime, setSize = st.ModTime(), st.Size()

	b, err := os.ReadFile(path)
	if err != nil {
		slog.Error(Name, "settings", err)
		return
	}
	var s Settings
	if err := json.Unmarshal(b, &s); err != nil {
		slog.Error(Name, "settings", err)
		return
	}
	applySettings(s)
}

func applySettings(s Settings) {
	mu.Lock()
	defer mu.Unlock()

	settings = s
	quick = nil
	quickKey = map[string]*engine{}

	for _, q := range s.Quicklinks {
		k := strings.ToLower(strings.TrimSpace(q.Keyword))
		if k == "" || strings.ContainsRune(k, ' ') {
			continue
		}
		e := &engine{key: k, name: q.Name, url: q.URL, icon: q.Icon, quick: true, rank: math.MaxInt32}
		if b, ok := byKey[strings.ToLower(q.Bang)]; ok && q.URL == "" {
			e.url, e.domain, e.category = b.url, b.domain, b.category
			if e.name == "" {
				e.name = b.name
			}
		}
		if e.url == "" {
			continue
		}
		if e.domain == "" {
			e.domain = cleanDomain("", e.url)
		}
		if e.name == "" {
			e.name = e.domain
		}
		e.lname, e.ldomain, e.lcat = strings.ToLower(e.name), strings.ToLower(e.domain), "quicklink"
		if _, dup := quickKey[k]; !dup {
			quick = append(quick, e)
			quickKey[k] = e
		}
	}

	for i, f := range s.Favorites {
		f = strings.ToLower(f)
		if e, ok := quickKey[f]; ok && e.fav == 0 {
			e.fav = i + 1
		} else if e, ok := byKey[f]; ok {
			e.fav = i + 1
		}
	}
	// Forget favorites removed since the last load.
	for _, e := range byKey {
		if e.fav != 0 && !slices.ContainsFunc(s.Favorites, func(f string) bool { return strings.EqualFold(f, e.key) }) {
			e.fav = 0
		}
	}
}

// resolve finds an engine by trigger or keyword; quicklinks win.
func resolve(key string) *engine {
	key = strings.ToLower(key)
	if e, ok := quickKey[key]; ok {
		return e
	}
	return byKey[key]
}

func defaultEngine() *engine {
	if e := resolve(settings.DefaultEngine); e != nil && e.template() {
		return e
	}
	if e := byKey["g"]; e != nil {
		return e
	}
	return &engine{key: "g", name: "Google", url: "https://www.google.com/search?q=%TERM%", domain: "google.com"}
}

// ── Query ────────────────────────────────────────────────────────────────

const (
	scoreScope = 100_000_000 // the scope row / an exact quicklink: always first
	scoreURL   = 1_000_000   // same as elephant's websearch
)

func Query(conn net.Conn, query string, single bool, exact bool, format uint8) []*pb.QueryResponse_Item {
	reloadSettings(false)

	mu.RLock()
	defer mu.RUnlock()

	var items []*pb.QueryResponse_Item

	if single {
		items = querySingle(query, exact)
	} else {
		items = queryMixed(query, exact)
	}

	if config.Favicons {
		for _, it := range items {
			if it.Icon == "" || !filepath.IsAbs(it.Icon) {
				favicons.want(conn, format, query, it)
			}
		}
	}

	return items
}

// querySingle: the "!" prefix (walker strips it).
func querySingle(q string, exact bool) []*pb.QueryResponse_Item {
	if key, term, ok := strings.Cut(q, " "); ok {
		if e := resolve(key); e != nil {
			return []*pb.QueryResponse_Item{scopeItem(e, strings.TrimSpace(term), true)}
		}
	}
	return browse(strings.ToLower(strings.TrimSpace(q)), exact)
}

// queryMixed: plain Spotlight queries — quicklinks, the default engine, URLs.
func queryMixed(q string, exact bool) []*pb.QueryResponse_Item {
	items := []*pb.QueryResponse_Item{}
	trim := strings.TrimSpace(q)
	if trim == "" {
		return items
	}

	// "yt" / "yt " / "yt lofi": the quicklink first.
	key, term, _ := strings.Cut(strings.TrimLeft(q, " "), " ")
	if e, ok := quickKey[strings.ToLower(key)]; ok {
		items = append(items, scopeItem(e, strings.TrimSpace(term), false))
	} else {
		// Otherwise quicklinks are ordinary fuzzy results.
		for _, e := range quick {
			s, pos, field := matchFuzzy(strings.ToLower(trim), e, exact)
			if s <= config.MinScore {
				continue
			}
			it := engineItem(e, false)
			it.Score = s
			if field == "text" {
				it.Fuzzyinfo = &pb.QueryResponse_Item_FuzzyInfo{Field: "text", Positions: pos}
			}
			items = append(items, it)
		}
	}

	if !strings.Contains(trim, " ") {
		if link := asURL(trim); link != "" {
			items = append(items, &pb.QueryResponse_Item{
				Identifier: "url:" + link,
				Text:       "Open " + link,
				Subtext:    "Website",
				Icon:       "web-browser",
				Actions:    []string{"open"},
				Provider:   Name,
				Score:      scoreURL,
			})
		}
	}

	d := defaultEngine()
	items = append(items, &pb.QueryResponse_Item{
		Identifier: "web:" + d.key,
		Text:       fmt.Sprintf("Search %s for “%s”", d.name, trim),
		Subtext:    d.domain,
		Icon:       iconFor(d),
		Actions:    []string{"search"},
		Provider:   Name,
		Score:      15,
	})

	return items
}

// scopeItem: the one row of a scope — "Search YouTube" (empty term, Enter
// scopes or opens the site), or "Search YouTube for “lofi”" (Enter searches).
func scopeItem(e *engine, term string, scoped bool) *pb.QueryResponse_Item {
	it := &pb.QueryResponse_Item{
		Provider: Name,
		Icon:     iconFor(e),
		Score:    scoreScope,
	}
	badge := "!" + e.key
	if !scoped && e.quick {
		badge = e.key
	}

	switch {
	case !e.template():
		it.Identifier = "home:" + e.key
		it.Text = "Open " + e.name
		it.Subtext = joinSub(badge, e.domain, kind(e))
		it.Actions = []string{"open"}
	case term == "" && scoped:
		it.Identifier = "home:" + e.key
		it.Text = "Search " + e.name
		it.Subtext = joinSub("Type to search", badge, e.domain)
		it.Actions = []string{"open"}
	case term == "":
		it.Identifier = "scope:" + e.key
		it.Text = "Search " + e.name
		it.Subtext = joinSub(badge, e.domain, kind(e))
		it.Actions = []string{"scope", "home"}
	default:
		it.Identifier = "search:" + e.key
		it.Text = fmt.Sprintf("Search %s for “%s”", e.name, term)
		it.Subtext = joinSub(badge, e.domain)
		it.Actions = []string{"search", "home"}
	}

	if scoped && !e.quick {
		it.Actions = append(it.Actions, "quicklink")
	}
	return it
}

func kind(e *engine) string {
	if e.quick {
		return "Quicklink"
	}
	return e.category
}

func engineItem(e *engine, bang bool) *pb.QueryResponse_Item {
	badge := e.key
	if bang || !e.quick {
		badge = "!" + e.key
	}
	it := &pb.QueryResponse_Item{
		Identifier: "scope:" + e.key,
		Text:       e.name,
		Subtext:    joinSub(badge, e.domain, kind(e)),
		Icon:       iconFor(e),
		Provider:   Name,
		Actions:    []string{"scope", "home"},
	}
	if !e.template() {
		it.Identifier = "home:" + e.key
		it.Actions = []string{"open"}
	}
	return it
}

func joinSub(parts ...string) string {
	out := parts[:0:0]
	for _, p := range parts {
		if p != "" {
			out = append(out, p)
		}
	}
	return strings.Join(out, "  ·  ")
}

type scored struct {
	e     *engine
	score int32
	pos   []int32
	field string
}

// browse ranks every engine against q: match quality first (exact trigger,
// trigger prefix, name/domain prefix, fuzzy), then quicklink/favorite,
// your own use, and popularity.
func browse(q string, exact bool) []*pb.QueryResponse_Item {
	max := config.MaxItems
	res := make([]scored, 0, 256)

	if q == "" {
		seen := map[*engine]bool{}
		add := func(e *engine, s int32) {
			if e != nil && !seen[e] {
				seen[e] = true
				res = append(res, scored{e: e, score: s})
			}
		}
		for i, e := range quick {
			add(e, int32(9_000_000-i))
		}
		for i, f := range settings.Favorites {
			add(resolve(f), int32(8_000_000-i))
		}
		for _, e := range bangs {
			if len(res) >= 2*max {
				break
			}
			add(e, int32(1_000_000+usageBonus(e.key))+popularity(e.rank))
		}
	} else {
		consider := func(e *engine) {
			tier, pos, field := matchTier(q, e, exact)
			if tier == 0 {
				return
			}
			s := tier + popularity(e.rank) + int32(usageBonus(e.key))
			if e.quick {
				s += 40_000
			} else if e.fav != 0 {
				s += 30_000
			}
			res = append(res, scored{e: e, score: s, pos: pos, field: field})
		}
		for _, e := range quick {
			consider(e)
		}
		for _, e := range bangs {
			if _, shadowed := quickKey[e.key]; shadowed {
				continue
			}
			consider(e)
		}
	}

	slices.SortStableFunc(res, func(a, b scored) int {
		if a.score != b.score {
			if a.score > b.score {
				return -1
			}
			return 1
		}
		return b.e.rank - a.e.rank
	})
	// One row per site: !yt, !youtube, !ytb are all "YouTube · youtube.com";
	// the best-scoring trigger (a quicklink's keyword, usually) stays.
	seen := make(map[string]bool, max)
	items := make([]*pb.QueryResponse_Item, 0, max)
	for _, r := range res {
		if len(items) >= max {
			break
		}
		site := r.e.lname + "|" + r.e.ldomain
		if seen[site] {
			continue
		}
		seen[site] = true

		it := engineItem(r.e, true)
		it.Score = r.score
		if r.field == "text" && len(r.pos) > 0 {
			it.Fuzzyinfo = &pb.QueryResponse_Item_FuzzyInfo{Field: "text", Positions: r.pos}
		}
		items = append(items, it)
	}
	return items
}

// popularity: DuckDuckGo's usage rank, log-scaled (≤ ~21k).
func popularity(r int) int32 {
	if r <= 0 {
		return 0
	}
	return int32(math.Log2(float64(r)+1) * 1000)
}

// matchTier scores one engine; 0 = no match.
func matchTier(q string, e *engine, exact bool) (int32, []int32, string) {
	switch {
	case e.key == q:
		return 900_000, nil, ""
	case strings.HasPrefix(e.key, q):
		return 800_000 - int32(min(len(e.key)-len(q), 50))*1000, nil, ""
	case strings.HasPrefix(e.lname, q):
		return 700_000 - int32(min(len(e.lname)-len(q), 50))*500, prefixPos(len(q)), "text"
	case wordPrefix(e.lname, q):
		return 650_000, nil, ""
	case strings.HasPrefix(strings.TrimPrefix(e.ldomain, "www."), q):
		return 600_000, nil, ""
	case exact:
		if strings.Contains(e.lname, q) || strings.Contains(e.ldomain, q) || strings.Contains(e.key, q) {
			return 300_000, nil, ""
		}
		return 0, nil, ""
	}

	s, pos, field := matchFuzzy(q, e, false)
	if s <= config.MinScore {
		return 0, nil, ""
	}
	return 100_000 + min(s, 1000)*100, pos, field
}

// matchFuzzy: elephant's fzf score against name, trigger, domain, category.
func matchFuzzy(q string, e *engine, exact bool) (int32, []int32, string) {
	var best int32
	var bestPos []int32
	field := ""

	try := func(target string, isText bool, penalty int32) {
		if !subsequence(q, target) {
			return
		}
		s, pos, _ := common.FuzzyScore(q, target, exact)
		s -= penalty
		if s > best {
			best, bestPos = s, pos
			field = ""
			if isText {
				field = "text"
			}
		}
	}

	try(e.lname, true, 0)
	try(e.key, false, 0)
	try(e.ldomain, false, 5)
	try(e.lcat, false, 15)
	return best, bestPos, field
}

// subsequence: every rune of q appears in s in order (cheap pre-filter).
func subsequence(q, s string) bool {
	i := 0
	qr := []rune(q)
	for _, r := range s {
		if i < len(qr) && r == qr[i] {
			i++
		}
	}
	return i == len(qr)
}

func wordPrefix(s, q string) bool {
	for i, r := range s {
		if i > 0 && !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			if strings.HasPrefix(s[i+1:], q) {
				return true
			}
		}
	}
	return false
}

func prefixPos(n int) []int32 {
	p := make([]int32, n)
	for i := range p {
		p[i] = int32(i)
	}
	return p
}

// ── Activate ─────────────────────────────────────────────────────────────

func Activate(single bool, identifier, action string, query string, args string, format uint8, conn net.Conn) {
	kind, key, _ := strings.Cut(identifier, ":")
	reloadSettings(false)

	mu.RLock()
	e := resolve(key)
	if kind == "web" {
		e = defaultEngine()
	}
	mu.RUnlock()

	switch action {
	case "scope":
		if e == nil {
			return
		}
		// Walker (patched) replaces its query: the scope is "!<key> ".
		handlers.ProviderUpdated <- "menus:%SETQUERY%!" + e.key + " "
	case "search":
		if e == nil {
			return
		}
		term := strings.TrimSpace(query)
		if kind != "web" {
			_, term, _ = strings.Cut(strings.TrimLeft(query, " "), " ")
			term = strings.TrimSpace(term)
		}
		open(fill(e.url, term))
		used(e.key)
	case "home":
		if e != nil {
			open(home(e.url))
			used(e.key)
		}
	case "open":
		switch {
		case kind == "url":
			open(key)
		case e != nil && !e.template():
			open(e.url)
			used(e.key)
		case e != nil:
			open(home(e.url))
			used(e.key)
		}
	case "quicklink":
		if e != nil {
			addQuicklink(e)
		}
	default:
		slog.Error(Name, "activate", "unknown action", "action", action)
	}
}

// fill puts the term into a URL like DuckDuckGo/unduck do
// (encodeURIComponent, "/" kept).
func fill(u, term string) string {
	enc := encodeURIComponent(term)
	enc = strings.ReplaceAll(enc, "%2F", "/")
	return strings.ReplaceAll(u, "%TERM%", enc)
}

func encodeURIComponent(s string) string {
	var b strings.Builder
	for _, c := range []byte(s) {
		if c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || strings.IndexByte("-_.!~*'()", c) >= 0 {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "%%%02X", c)
		}
	}
	return b.String()
}

func home(u string) string {
	p, err := url.Parse(strings.ReplaceAll(u, "%TERM%", ""))
	if err != nil || p.Host == "" {
		return u
	}
	return p.Scheme + "://" + p.Host + "/"
}

func open(target string) {
	run(fmt.Sprintf("%s %s %s", common.LaunchPrefix(), config.Command, shellescape.Quote(target)))
}

func run(command string) {
	cmd := exec.Command("sh", "-c", strings.TrimSpace(command))
	cmd.SysProcAttr = &syscall.SysProcAttr{Setsid: true}
	if err := cmd.Start(); err != nil {
		slog.Error(Name, "run", err)
		return
	}
	go cmd.Wait()
}

// addQuicklink appends a quicklink for e to the settings file (keyword = the
// trigger, made unique) and opens Settings → Spotlight to edit it.
func addQuicklink(e *engine) {
	mu.Lock()
	s := settings
	kw := e.key
	for n := 2; ; n++ {
		if _, taken := quickKey[kw]; !taken {
			break
		}
		kw = fmt.Sprintf("%s%d", e.key, n)
	}
	// First in the list: it shows at the top of Settings → Spotlight.
	s.Quicklinks = append([]Quicklink{{
		ID:      fmt.Sprintf("ql-%d", time.Now().UnixNano()),
		Keyword: kw,
		Name:    e.name,
		Bang:    e.key,
	}}, s.Quicklinks...)
	mu.Unlock()

	if err := writeJSON(config.Settings, s); err != nil {
		slog.Error(Name, "quicklink", err)
		return
	}
	reloadSettings(true)

	if config.SettingsCmd != "" {
		run(config.SettingsCmd)
	}
}

func writeJSON(path string, v any) error {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, append(b, '\n'), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// ── Usage (your own ranking) ─────────────────────────────────────────────

var (
	usageMu sync.Mutex
	usage   = map[string]int{}
)

func usageFile() string { return common.CacheFile("bangs_usage.json") }

func loadUsage() {
	if b, err := os.ReadFile(usageFile()); err == nil {
		_ = json.Unmarshal(b, &usage)
	}
}

func usageBonus(key string) int {
	usageMu.Lock()
	n := usage[key]
	usageMu.Unlock()
	return min(n, 25) * 4000
}

func used(key string) {
	usageMu.Lock()
	usage[key]++
	b, _ := json.Marshal(usage)
	usageMu.Unlock()
	_ = os.MkdirAll(filepath.Dir(usageFile()), 0o755)
	_ = os.WriteFile(usageFile(), b, 0o600)
}

