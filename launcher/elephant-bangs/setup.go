// Package main is elephant's "bangs" provider for the Loft Spotlight:
// DuckDuckGo !bangs (unduck's list) and Quicklinks, with a sub-search scope.
//
//	!            browse: quicklinks, favorites, then the most used bangs
//	!nixpk       fuzzy on trigger, name, domain and category; Enter/Tab scopes
//	!nixpkgs ␣   the scope: one row "Search NixOS Packages" — type the term
//	!yt lofi     Enter searches YouTube for "lofi"
//	yt           (no "!") a quicklink keyword: top result; Enter scopes ("!yt ")
//	yt lofi      Enter searches right away
//
// Scoping replaces walker's query text: the provider sends
// "menus:%SETQUERY%!<trigger> " on elephant's menu channel, which the patched
// walker (launcher/walker-set-query.patch) turns into set_input_text. Leaving a
// scope needs nothing: Backspace deletes the space and "!nixpkgs" browses again.
//
// It also answers plain queries with the default engine ("Search Google for
// …") and URLs ("Open https://…"), replacing elephant's websearch there.
//
// Built into elephant's own provider tree (nix/packages.nix loft-elephant),
// so the plugin matches the host binary's toolchain and dependencies exactly.
