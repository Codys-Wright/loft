"""DuckDuckGo-style !bangs for the launcher (unduck's bang list → elephant).

Reads unduck's src/bang.ts (github.com/T3-Content/unduck — DuckDuckGo's bang
list as a JS array) and writes elephant's websearch.toml: one engine per bang,
triggered by "!<bang> " (the trailing space keeps "!y" from swallowing
"!yt" — elephant matches prefixes with HasPrefix), plus the default engine
that plain queries offer.

usage: python3 bangs.py bang.ts out.toml [--default NAME=URL]
"""

from __future__ import annotations

import json
import re
import sys


def parse(ts: str) -> list[dict]:
    body = ts[ts.index("[") : ts.rindex("]") + 1]
    body = re.sub(r"(?m)^\s*([a-z]+):", r'"\1":', body)  # quote keys
    # single-quoted JS strings (they hold double quotes) → JSON strings
    body = re.sub(
        r"(\"[a-z]+\":\s*)'((?:[^'\\]|\\.)*)'",
        lambda m: m.group(1) + json.dumps(m.group(2).replace("\\'", "'")),
        body,
    )
    body = re.sub(r",(\s*[}\]])", r"\1", body)  # trailing commas
    return json.loads(body)


def toml_str(s: str) -> str:
    # JSON string escapes are valid TOML basic-string escapes.
    return json.dumps(s, ensure_ascii=False)


def main() -> None:
    args = sys.argv[1:]
    default = ("Google", "https://www.google.com/search?q=%TERM%")
    if "--default" in args:
        i = args.index("--default")
        name, url = args[i + 1].split("=", 1)
        default = (name, url)
        del args[i : i + 2]
    src, out = args
    bangs = parse(open(src, encoding="utf-8").read())

    seen: set[str] = set()
    lines = [
        "# Generated by launcher/bangs.py from unduck's bang list — do not edit.",
        "# Type !<bang> <query> in Spotlight, e.g. !yt lofi, !gh niri, !w Avatar.",
        "engines_as_actions = false",
        "history = true",
        'text_prefix = "Search "',
        "",
        "[[entries]]",
        f"name = {toml_str(default[0])}",
        f"url = {toml_str(default[1])}",
        "default = true",
        "",
    ]
    # Most-used first, so a duplicate trigger keeps the popular engine.
    for b in sorted(bangs, key=lambda b: -int(b.get("r") or 0)):
        t = (b.get("t") or "").strip()
        url = b.get("u") or ""
        if not t or not url or t in seen:
            continue
        seen.add(t)
        lines += [
            "[[entries]]",
            f"name = {toml_str(b.get('s') or t)}",
            f"prefix = {toml_str('!' + t + ' ')}",
            f"url = {toml_str(url.replace('{{{s}}}', '%TERM%'))}",
            "",
        ]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"bangs: {len(seen)} engines → {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
