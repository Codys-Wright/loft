//! overrides/niri.json → overrides/niri.kdl.
//!
//! The fragment is included LAST by the Loft sessions (after base.kdl, the
//! shell binds and the theme), so its merged sections win. niri resolves
//! `output` blocks differently: the FIRST block matching an output wins,
//! whole. So the sessions also include the fragment FIRST, and each output
//! block we write carries the user's own settings for that output (copied
//! from their matching block) with only our fields replaced.
//!
//! Blocks niri replaces whole on redefinition (`input.mouse`, `xkb`,
//! `struts`, …) are written the same way: the effective block from the
//! config with our fields changed, so overriding one field never drops the
//! user's others.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use serde_json::{Map, Value};

use crate::config::{self, ConfigTree};
use crate::kdl_out::{self, Node, Val};
use crate::keys::KEYS;
use crate::outputs::{self, Outputs};
use crate::state::{Overrides, Paths, write_atomic};

pub const HEADER: &str = "\
// Generated by loft-niri from niri.json (runtime overrides from Loft
// Settings). Do not edit: change settings in the UI or with `loft-niri`.
// Sessions include this file first (so its output blocks win: niri uses the
// first matching `output`) and last (so everything else wins).
";

/// Settings fields an output override may replace in the user's block.
const OUTPUT_FIELDS: &[(&str, &[&str])] = &[
    ("off", &["off"]),
    ("mode", &["mode", "modeline"]),
    ("scale", &["scale"]),
    ("transform", &["transform"]),
    ("position", &["position"]),
    ("vrr", &["variable-refresh-rate"]),
];

/// The KDL nodes for the non-output overrides.
pub fn render_settings(ov: &Overrides, base: Option<&ConfigTree>) -> Vec<Node> {
    // unit path → the rendered unit node; kept in registry order.
    let mut units: Vec<(Vec<&str>, Node)> = Vec::new();
    for def in KEYS {
        let Some(v) = ov.get(def.key) else { continue };
        let Ok(v) = def.parse(v) else { continue };
        let unit: Vec<&str> = def.unit.to_vec();
        let pos = match units.iter().position(|(u, _)| *u == unit) {
            Some(p) => p,
            None => {
                let name = *unit.last().unwrap();
                let node = match def.field {
                    // A replace-whole block: start from the effective one.
                    Some(_) => base
                        .and_then(|t| t.find_last(def.unit))
                        .map(|n| {
                            let mut n = Node::from_kdl(n.node);
                            n.args.clear();
                            n.props.clear();
                            n
                        })
                        .unwrap_or_else(|| Node::new(name)),
                    None => Node::new(name),
                };
                units.push((unit, node));
                units.len() - 1
            }
        };
        let node = &mut units[pos].1;
        match def.field {
            Some(f) => {
                node.remove_children(f);
                if let Some(c) = def.to_node(f, &v) {
                    node.children.push(c);
                }
            }
            None => {
                if let Some(n) = def.to_node(def.unit.last().unwrap(), &v) {
                    *node = n;
                }
            }
        }
    }

    // Nest the units under their parents: input > keyboard > xkb, …
    let mut roots: Vec<Node> = Vec::new();
    for (path, node) in units {
        let (first, rest) = path.split_first().unwrap();
        if rest.is_empty() {
            roots.push(node);
            continue;
        }
        let root = match roots.iter().position(|r| r.name == *first) {
            Some(i) => &mut roots[i],
            None => {
                roots.push(Node::new(*first));
                roots.last_mut().unwrap()
            }
        };
        let mut cur = root;
        for p in &rest[..rest.len() - 1] {
            cur = cur.child_mut(p);
        }
        cur.children.push(node);
    }
    roots
}

/// The user's first `output` block matching this output (niri's rule).
fn base_output<'a>(
    tree: &'a ConfigTree,
    identity: &str,
    live: Option<&niri_ipc::Output>,
) -> Option<&'a kdl::KdlNode> {
    tree.find_all(&["output"])
        .into_iter()
        .map(|n| n.node)
        .find(|n| {
            let Some(name) = n
                .entries()
                .iter()
                .find(|e| e.name().is_none())
                .and_then(|e| e.value().as_string())
            else {
                return false;
            };
            match live {
                Some(o) => outputs::matches(o, name),
                None => name.eq_ignore_ascii_case(identity),
            }
        })
}

pub fn render_output(
    identity: &str,
    rec: &Map<String, Value>,
    base: Option<&kdl::KdlNode>,
) -> Node {
    let mut node = Node::new("output").arg(Val::Str(identity.to_string()));
    if let Some(b) = base {
        node.children = b.iter_children().map(Node::from_kdl).collect();
    }
    for (field, kdl_names) in OUTPUT_FIELDS {
        let Some(v) = rec.get(*field) else { continue };
        for n in *kdl_names {
            node.remove_children(n);
        }
        let child = match *field {
            "off" => v.as_bool().filter(|b| *b).map(|_| Node::new("off")),
            "mode" => v
                .as_str()
                .filter(|s| *s != "auto")
                .map(|s| Node::new("mode").arg(Val::Str(s.to_string()))),
            "scale" => v.as_f64().map(|s| Node::new("scale").arg(Val::Number(s))),
            "transform" => v
                .as_str()
                .map(|s| Node::new("transform").arg(Val::Str(s.to_string()))),
            "position" => v.as_object().map(|p| {
                Node::new("position")
                    .prop(
                        "x",
                        Val::Int(p.get("x").and_then(Value::as_i64).unwrap_or(0)),
                    )
                    .prop(
                        "y",
                        Val::Int(p.get("y").and_then(Value::as_i64).unwrap_or(0)),
                    )
            }),
            "vrr" => match v {
                Value::Bool(true) => Some(Node::new("variable-refresh-rate")),
                Value::String(s) if s == "on-demand" => {
                    Some(Node::new("variable-refresh-rate").prop("on-demand", Val::Bool(true)))
                }
                _ => None,
            },
            _ => None,
        };
        if let Some(c) = child {
            node.children.push(c);
        }
    }
    node
}

/// Escape a literal for a niri regex (`match app-id="^…$"`).
pub fn regex_literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if "\\.+*?()|[]{}^$".contains(c) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// Per-app window rules (`window-rules`: app-id → { "open-on-workspace",
/// "open-on-output" }) — the dock's "Assign To". Named workspaces are not
/// declared here: the fragment is included twice, and a twice-declared
/// workspace exists twice. The shell names the workspace live instead.
pub fn render_rules(ov: &Overrides) -> Vec<Node> {
    let mut nodes = Vec::new();
    if let Some(rules) = ov.0.get("window-rules").and_then(Value::as_object) {
        let ordered: BTreeMap<_, _> = rules.iter().collect();
        for (app, rec) in ordered {
            let mut n = Node::new("window-rule").child(
                Node::new("match").prop("app-id", Val::Str(format!("^{}$", regex_literal(app)))),
            );
            let mut any = false;
            for key in ["open-on-workspace", "open-on-output"] {
                if let Some(v) = rec.get(key).and_then(Value::as_str) {
                    n = n.child(Node::new(key).arg(Val::Str(v.to_string())));
                    any = true;
                }
            }
            if any {
                nodes.push(n);
            }
        }
    }
    nodes
}

/// The whole fragment.
pub fn render(ov: &Overrides, base: Option<&ConfigTree>, live: Option<&Outputs>) -> String {
    let mut nodes = Vec::new();
    if let Some(outs) = ov.outputs() {
        let ordered: BTreeMap<_, _> = outs.iter().collect();
        for (id, rec) in ordered {
            let Some(rec) = rec.as_object() else { continue };
            let live_o = live.and_then(|l| outputs::find(l, id));
            let b = base.and_then(|t| base_output(t, id, live_o));
            nodes.push(render_output(id, rec, b));
        }
    }
    nodes.extend(render_rules(ov));
    nodes.extend(render_settings(ov, base));
    let mut out = String::from(HEADER);
    if !nodes.is_empty() {
        out.push('\n');
        out.push_str(&kdl_out::write_doc(&nodes));
    }
    out
}

/// The config tree without our own fragment: what "from config" means.
pub fn base_tree(entry: Option<&Path>, paths: &Paths) -> Option<ConfigTree> {
    let entry = entry?;
    let ours = config::normalize(&paths.kdl);
    ConfigTree::load(entry, &move |p| p == ours).ok()
}

pub fn find_niri() -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|d| d.join("niri"))
        .find(|p| p.is_file())
}

/// `niri validate` the session's config with `candidate` in place of the
/// overrides fragment (or the candidate alone when there is no entry config).
pub fn validate(niri: &Path, entry: Option<&Path>, paths: &Paths, candidate: &Path) -> Result<()> {
    let scratch = paths
        .dir()
        .join(format!(".validate-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&scratch);
    std::fs::create_dir_all(&scratch)?;
    let result = (|| {
        let target = match entry {
            Some(e) if e.exists() => config::materialize(e, &paths.kdl, candidate, &scratch)?,
            _ => candidate.to_path_buf(),
        };
        let out = Command::new(niri)
            .arg("validate")
            .arg("-c")
            .arg(&target)
            .output()
            .with_context(|| format!("running {} validate", niri.display()))?;
        if !out.status.success() {
            let msg = format!(
                "{}{}",
                String::from_utf8_lossy(&out.stdout),
                String::from_utf8_lossy(&out.stderr)
            );
            bail!("niri rejected the overrides:\n{}", msg.trim());
        }
        Ok(())
    })();
    let _ = std::fs::remove_dir_all(&scratch);
    result
}

pub struct RenderOpts<'a> {
    pub entry: Option<&'a Path>,
    pub validate: bool,
    pub reload: bool,
    pub live: Option<&'a Outputs>,
}

pub enum RenderResult {
    Unchanged,
    Written,
}

/// Render, validate, atomically swap in, and ask niri to reload.
pub fn render_to_disk(paths: &Paths, opts: &RenderOpts) -> Result<RenderResult> {
    let ov = Overrides::load(&paths.json)?;
    let base = base_tree(opts.entry, paths);
    let text = render(&ov, base.as_ref(), opts.live);
    if std::fs::read_to_string(&paths.kdl).ok().as_deref() == Some(text.as_str()) {
        return Ok(RenderResult::Unchanged);
    }
    std::fs::create_dir_all(paths.dir())?;
    let candidate = paths
        .dir()
        .join(format!(".niri.kdl.candidate-{}", std::process::id()));
    std::fs::write(&candidate, &text)?;
    if opts.validate {
        let res = match find_niri() {
            Some(niri) => validate(&niri, opts.entry, paths, &candidate),
            None => Err(anyhow::anyhow!(
                "`niri` is not on PATH, cannot validate (pass --no-validate to skip)"
            )),
        };
        if let Err(e) = res {
            let _ = std::fs::remove_file(&candidate);
            return Err(e);
        }
    }
    std::fs::rename(&candidate, &paths.kdl).or_else(|_| write_atomic(&paths.kdl, &text))?;
    if opts.reload {
        crate::ipc::reload_config();
    }
    Ok(RenderResult::Written)
}

