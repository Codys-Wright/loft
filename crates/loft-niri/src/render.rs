    #[test]
    fn rendered_fragment_passes_niri_validate() {
        let Some(niri) = find_niri() else {
            eprintln!("niri not on PATH; skipping");
            return;
        };
        let d = scratch("render-validate");
        let paths = Paths::new(d.join("state"));
        std::fs::create_dir_all(paths.dir()).unwrap();
        std::fs::write(
            d.join("config.kdl"),
            format!(
                "include optional=true \"{0}\"\nlayout {{ gaps 4; }}\ninclude optional=true \"{0}\"\n",
                paths.kdl.display()
            ),
        )
        .unwrap();
        let o = ov(json!({
            "input": { "mouse": { "accel-speed": 0.1, "natural-scroll": true }, "touchpad": { "tap": true },
                       "keyboard": { "repeat-delay": 250, "xkb": { "layout": "us" } } },
            "layout": { "gaps": 10, "default-column-width": 0.5, "preset-column-widths": [0.5, 1], "struts": { "top": 4 },
                        "center-focused-column": "always" },
            "animations": { "slowdown": 1.5, "off": true },
            "outputs": { "Samsung Electric Company Odyssey G95NC H1AK500000": { "mode": "5120x1440@239.761", "scale": 1, "transform": "flipped-90", "position": { "x": 0, "y": 0 }, "vrr": "on-demand" } }
        }));
        let cand = d.join("cand.kdl");
        std::fs::write(&cand, render(&o, None, None)).unwrap();
        validate(&niri, Some(&d.join("config.kdl")), &paths, &cand).unwrap();

        std::fs::write(&cand, format!("{HEADER}layout {{ gaps \"wide\"; }}\n")).unwrap();
        assert!(validate(&niri, Some(&d.join("config.kdl")), &paths, &cand).is_err());
    }

    #[test]
    fn window_rules_and_workspaces() {
        let o = ov(json!({
            "window-rules": {
                "org.gnome.Nautilus": { "open-on-workspace": "Desktop 2" },
                "empty": {}
            }
        }));
        let expected = format!(
            r#"{HEADER}
window-rule {{
    match app-id="^org\\.gnome\\.Nautilus$"
    open-on-workspace "Desktop 2"
}}
"#
        );
        assert_eq!(render(&o, None, None), expected);
        if let Some(niri) = find_niri() {
            let d = scratch("render-rules");
            let paths = Paths::new(d.join("state"));
            std::fs::create_dir_all(paths.dir()).unwrap();
            std::fs::write(
                d.join("config.kdl"),
                format!(
                    "include optional=true \"{0}\"\ninclude optional=true \"{0}\"\n",
                    paths.kdl.display()
                ),
            )
            .unwrap();
            let cand = d.join("cand.kdl");
            std::fs::write(&cand, &expected).unwrap();
            validate(&niri, Some(&d.join("config.kdl")), &paths, &cand).unwrap();
        }
    }

