    #[test]
    fn replaced_blocks_keep_the_users_other_fields() {
        let d = scratch("render-base");
        std::fs::write(
            d.join("config.kdl"),
            r#"
input {
    keyboard { xkb { layout "us"; variant "dvorak"; } }
    mouse { accel-speed 0.5; left-handed; natural-scroll; }
}
layout { struts { left 10; right 10; } }
input { mouse { accel-speed 0.3; middle-emulation; natural-scroll; } }
"#,
        )
        .unwrap();
        let tree = ConfigTree::load(&d.join("config.kdl"), &|_| false).unwrap();
        let o = ov(json!({
            "input": { "mouse": { "natural-scroll": false }, "keyboard": { "xkb": { "layout": "de" } } },
            "layout": { "struts": { "top": 24 } }
        }));
        let out = render(&o, Some(&tree), None);
        // The LAST mouse block is the effective one: middle-emulation kept,
        // left-handed (from the earlier, replaced block) not resurrected.
        assert!(
            out.contains("    mouse {\n        accel-speed 0.3\n        middle-emulation\n    }\n"),
            "{out}"
        );
        assert!(out.contains("        xkb {\n            variant \"dvorak\"\n            layout \"de\"\n        }\n"), "{out}");
        assert!(
            out.contains(
                "    struts {\n        left 10\n        right 10\n        top 24\n    }\n"
            ),
            "{out}"
        );
    }

