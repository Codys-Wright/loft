//! Spaces → `<state>/overrides/spaces.kdl` (SPACES.md §3.2, §6.2, §7).
//!
//! - one `workspace "<name>" { open-on-output "<identity>"; layout { … } }`
//!   per workspace of every space (singletons and instances), in space
//!   order, so declared workspaces exist from niri's start and sit on each
//!   display in space order;
//! - window rules for the apps whose app-id Loft sets (`^loft\.…`), so niri
//!   places them at map time;
//! - the space binds (Mod+1…9, Mod+Shift+1…9, Mod+Ctrl+Left/Right,
//!   Mod+Page_Up/Page_Down; Mod+Alt+Page_Up/Page_Down keep niri's own
//!   per-display workspace up / down).
//!
//! The file is included ONCE (after base.kdl and the theme): a workspace
//! declared twice exists twice.

use serde_json::{Map, Value};

use super::apps;
use super::model::{Fold, Space};
use super::roles::{self, Display};
use crate::kdl_out::{self, Node, Val};

pub const HEADER: &str = "\
// Generated by `loft-niri space render` from the spaces (SPACES.md). Do not
// edit: change the spaces, then render again. Included once, after base.kdl.
";

#[derive(Debug, Clone)]
pub struct RenderOpts<'a> {
    /// The command the binds spawn (`loft-niri`).
    pub bin: &'a str,
    pub binds: bool,
}

impl Default for RenderOpts<'_> {
    fn default() -> Self {
        RenderOpts {
            bin: "loft-niri",
            binds: true,
        }
    }
}

/// KDL-in-JSON → nodes: objects are blocks, `true` a bare flag, `false` /
/// null omitted, numbers / strings the node's argument, arrays several.
pub fn json_to_nodes(m: &Map<String, Value>) -> Vec<Node> {
    let mut out = Vec::new();
    for (k, v) in m {
        let mut n = Node::new(k.as_str());
        match v {
            Value::Bool(false) | Value::Null => continue,
            Value::Bool(true) => {}
            Value::Object(o) => n.children = json_to_nodes(o),
            Value::Array(a) => n.args = a.iter().filter_map(val).collect(),
            other => n.args.extend(val(other)),
        }
        out.push(n);
    }
    out
}

fn val(v: &Value) -> Option<Val> {
    Some(match v {
        Value::String(s) => Val::Str(s.clone()),
        Value::Number(n) => match n.as_i64() {
            Some(i) => Val::Int(i),
            None => Val::Float(n.as_f64()?),
        },
        Value::Bool(b) => Val::Bool(*b),
        _ => return None,
    })
}

/// Workspace declarations: every space's workspaces in space order (the
/// space's main workspace first, stacked folds right after it).
pub fn render_workspaces(spaces: &[&Space], displays: &[Display], main: Option<&str>) -> Vec<Node> {
    let mut nodes = Vec::new();
    for s in spaces {
        let r = roles::resolve(s, displays, main);
        for (role, b) in s.workspaces() {
            let folded = r.folded.iter().find(|f| f.role == role);
            if folded.is_some_and(|f| f.fold != Fold::Stack) {
                continue; // columns / skip: no workspace while the display is away
            }
            let mut n = Node::new("workspace").arg(Val::Str(b.workspace.clone()));
            if let Some(d) = r.display_of(&b.workspace) {
                n = n.child(Node::new("open-on-output").arg(Val::Str(d.identity().to_string())));
            }
            if let Some(l) = b.layout.as_ref().filter(|l| !l.is_empty()) {
                let mut layout = Node::new("layout");
                layout.children = json_to_nodes(l);
                n = n.child(layout);
            }
            nodes.push(n);
        }
    }
    nodes
}

/// niri window rules for apps Loft names itself (`match.appId` an exact
/// `^loft\.…$`): open on their workspace, at their width, unfocused. The
/// workspace follows the layout like spin-up does (`apps::specs`): a
/// `columns` fold opens them on main's workspace, `skip` writes no rule.
/// Without displays (niri unreachable) each app's declared workspace.
pub fn render_rules(spaces: &[&Space], displays: &[Display], main: Option<&str>) -> Vec<Node> {
    let mut nodes = Vec::new();
    for s in spaces {
        // (workspace, app, folded into main's workspace as a column)
        let mut apps: Vec<(String, &Value, bool)> = Vec::new();
        if displays.is_empty() {
            for (_, b) in s.workspaces() {
                apps.extend(b.apps.iter().map(|a| (b.workspace.clone(), a, false)));
            }
        } else {
            let r = roles::resolve(s, displays, main);
            let (specs, _) = apps::specs(s, &r, apps::UNIT_PREFIX, "");
            for sp in specs {
                let app = s.workspaces().into_iter().find_map(|(_, b)| {
                    b.apps
                        .iter()
                        .find(|a| a.get("id").and_then(Value::as_str) == Some(sp.app.as_str()))
                });
                if let Some(a) = app {
                    apps.push((sp.workspace, a, sp.folded));
                }
            }
        }
        for (ws, app, folded) in apps {
            let Some(re) = app
                .pointer("/match/appId")
                .and_then(Value::as_str)
                .filter(|re| re.starts_with("^loft\\.") && re.ends_with('$'))
            else {
                continue;
            };
            let mut n = Node::new("window-rule")
                .child(Node::new("match").prop("app-id", Val::Str(re.to_string())))
                .child(Node::new("open-on-workspace").arg(Val::Str(ws)))
                .child(Node::new("open-focused").arg(Val::Bool(false)));
            let width = app.get("width").and_then(Value::as_f64);
            if folded {
                // A column among main's (as spin-up sizes it).
                n = n.child(Node::new("default-column-width").child(
                    Node::new("proportion").arg(Val::Float(width.unwrap_or(apps::FOLD_WIDTH))),
                ));
                nodes.push(n);
                continue;
            }
            if let Some(w) = width {
                n = n.child(
                    Node::new("default-column-width")
                        .child(Node::new("proportion").arg(Val::Float(w))),
                );
            }
            match app.get("open").and_then(Value::as_str) {
                Some("maximized") => n = n.child(Node::new("open-maximized").arg(Val::Bool(true))),
                Some("fullscreen") => {
                    n = n.child(Node::new("open-fullscreen").arg(Val::Bool(true)))
                }
                Some("floating") => n = n.child(Node::new("open-floating").arg(Val::Bool(true))),
                _ => {}
            }
            nodes.push(n);
        }
    }
    nodes
}

fn spawn(bin: &str, args: &[&str]) -> Node {
    let mut n = Node::new("spawn").arg(Val::Str(bin.to_string()));
    for a in args {
        n = n.arg(Val::Str(a.to_string()));
    }
    n
}

/// The space binds (§6.2, §12.6): positions 1…9 are the active spaces in order.
pub fn render_binds(spaces: &[&Space], bin: &str) -> Node {
    let mut b = Node::new("binds");
    for (i, s) in spaces.iter().take(9).enumerate() {
        let n = i + 1;
        b = b.child(
            Node::new(format!("Mod+{n}"))
                .prop(
                    "hotkey-overlay-title",
                    Val::Str(format!("Space: {}", s.name)),
                )
                .child(spawn(bin, &["space", "focus", &s.id])),
        );
    }
    for (i, s) in spaces.iter().take(9).enumerate() {
        let n = i + 1;
        b = b.child(
            Node::new(format!("Mod+Shift+{n}"))
                .prop(
                    "hotkey-overlay-title",
                    Val::Str(format!("Move Window to {}", s.name)),
                )
                .child(spawn(bin, &["space", "move-window", &s.id])),
        );
    }
    for (key, dir, title) in [
        ("Mod+Ctrl+Left", "prev", "Previous Space"),
        ("Mod+Ctrl+Right", "next", "Next Space"),
        ("Mod+Page_Up", "prev", ""),
        ("Mod+Page_Down", "next", ""),
    ] {
        let mut n = Node::new(key);
        n = if title.is_empty() {
            n.prop("hotkey-overlay-title", Val::Null)
        } else {
            n.prop("hotkey-overlay-title", Val::Str(title.into()))
        };
        b = b.child(n.child(spawn(bin, &["space", dir])));
    }
    // niri's own per-display workspace up / down: the escape hatch.
    b = b
        .child(Node::new("Mod+Alt+Page_Up").child(Node::new("focus-workspace-up")))
        .child(Node::new("Mod+Alt+Page_Down").child(Node::new("focus-workspace-down")));
    b
}

/// The whole `spaces.kdl`.
pub fn render(
    spaces: &[&Space],
    displays: &[Display],
    main: Option<&str>,
    opts: &RenderOpts,
) -> String {
    let mut nodes = render_workspaces(spaces, displays, main);
    nodes.extend(render_rules(spaces, displays, main));
    if opts.binds {
        nodes.push(render_binds(spaces, opts.bin));
    }
    let mut out = String::from(HEADER);
    if !nodes.is_empty() {
        out.push('\n');
        out.push_str(&kdl_out::write_doc(&nodes));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::render::find_niri;
    use crate::spaces::model::tests::catalog;
    use crate::spaces::roles::tests::desk;
    use serde_json::json;
    use std::path::PathBuf;
    use std::process::Command;

    fn golden(name: &str) -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("tests/golden")
            .join(name)
    }

    /// Compare with a golden file; `LOFT_UPDATE_GOLDEN=1` rewrites it.
    fn check_golden(name: &str, got: &str) {
        let p = golden(name);
        if std::env::var_os("LOFT_UPDATE_GOLDEN").is_some() {
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(&p, got).unwrap();
        }
        let want = std::fs::read_to_string(&p)
            .unwrap_or_else(|_| panic!("{} missing (LOFT_UPDATE_GOLDEN=1 writes it)", p.display()));
        assert_eq!(
            got, want,
            "{name} differs from the golden file (LOFT_UPDATE_GOLDEN=1 to accept)"
        );
    }

    /// `niri validate` a config: the repo's base.kdl, then the fragment.
    pub fn niri_validate(name: &str, text: &str) {
        let Some(niri) = find_niri() else {
            eprintln!("niri not on PATH; skipping validate");
            return;
        };
        let d = crate::config::tests_support::scratch(name);
        let base = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../niri/base.kdl");
        std::fs::write(d.join("spaces.kdl"), text).unwrap();
        std::fs::write(
            d.join("config.kdl"),
            format!("include \"{}\"\ninclude \"spaces.kdl\"\n", base.display()),
        )
        .unwrap();
        let out = Command::new(niri)
            .args(["validate", "-c"])
            .arg(d.join("config.kdl"))
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "niri validate:\n{}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        );
    }

    #[test]
    fn golden_three_displays() {
        let cat = catalog();
        let text = render(&cat.active(), &desk(), None, &RenderOpts::default());
        check_golden("spaces-three.kdl", &text);
        niri_validate("spaces-three", &text);
    }

    #[test]
    fn golden_laptop_folds() {
        let cat = catalog();
        let laptop = vec![Display {
            name: "eDP-1".into(),
            identity: "BOE 0x0BCA Unknown".into(),
            x: 0,
            y: 0,
            width: 1920,
            height: 1200,
        }];
        let text = render(
            &cat.active(),
            &laptop,
            None,
            &RenderOpts {
                bin: "/bin/loft-niri",
                binds: false,
            },
        );
        check_golden("spaces-laptop.kdl", &text);
        niri_validate("spaces-laptop", &text);
    }

    #[test]
    fn layout_json_to_kdl() {
        let m = json!({ "struts": { "top": 0, "bottom": 2.5 }, "focus-ring": { "off": true },
                        "border": { "off": false }, "gaps": 8, "x": null,
                        "preset-column-widths": { "proportion": [0.5] } });
        let nodes = json_to_nodes(m.as_object().unwrap());
        assert_eq!(
            kdl_out::write_doc(&nodes),
            "border\n\nfocus-ring {\n    off\n}\n\ngaps 8\n\npreset-column-widths {\n    proportion 0.5\n}\n\nstruts {\n    bottom 2.5\n    top 0\n}\n"
        );
    }

    #[test]
    fn rules_follow_the_fold() {
        let cat = catalog();
        let mut loft = cat.find("proj-loft").unwrap().clone();
        // Apps that set their own app-id (the built-in Chromium apps can't).
        for b in loft.displays.values_mut() {
            if let crate::spaces::model::Binding::Bound(b) = b {
                for a in &mut b.apps {
                    let id = a["id"].as_str().unwrap().to_string();
                    a["match"] = json!({ "appId": format!("^loft\\.proj-loft\\.{id}$") });
                }
            }
        }
        let laptop = vec![Display {
            name: "eDP-1".into(),
            identity: "BOE".into(),
            x: 0,
            y: 0,
            width: 1920,
            height: 1200,
        }];
        let rule_ws = |s: &Space, d: &[Display]| -> Vec<String> {
            render_rules(&[s], d, None)
                .iter()
                .map(|n| kdl_out::write_doc(std::slice::from_ref(n)))
                .filter_map(|t| {
                    t.lines()
                        .find(|l| l.contains("open-on-workspace"))
                        .map(|l| l.trim().to_string())
                })
                .collect()
        };
        let three = rule_ws(&loft, &desk());
        assert_eq!(
            three,
            [
                "open-on-workspace \"loft\"",
                "open-on-workspace \"loft\"",
                "open-on-workspace \"loft/left\"",
                "open-on-workspace \"loft/right\""
            ]
        );
        assert_eq!(rule_ws(&loft, &laptop), three, "stack keeps the workspaces");
        loft.fold = Fold::Columns;
        assert_eq!(rule_ws(&loft, &laptop), ["open-on-workspace \"loft\""; 4]);
        // Folded docs: a half column in main's workspace, not maximized.
        let docs = kdl_out::write_doc(&render_rules(&[&loft], &laptop, None)[0..1]);
        assert!(
            docs.contains("proportion 0.5") && !docs.contains("open-maximized"),
            "{docs}"
        );
        loft.fold = Fold::Skip;
        assert_eq!(rule_ws(&loft, &laptop), ["open-on-workspace \"loft\""; 2]);
        assert_eq!(rule_ws(&loft, &[]), three);
    }

    #[test]
    fn no_spaces_render_the_header_only() {
        assert_eq!(
            render(
                &[],
                &[],
                None,
                &RenderOpts {
                    bin: "x",
                    binds: false
                }
            ),
            HEADER
        );
    }
}
