"""The library: one folder for every theme pack and wallpaper.

Root: $STUDIO_LIBRARY (default ~/Documents/Themes; `none` turns it off).

  Packs/<pack>/                     installed theme packs (real files; `studio theme install` puts them here)
  Wallpapers/Topics/<Topic>/        curated images by topic (real files; `studio library add`)
  Wallpapers/Colors/<Family>/       generated: symlinks by dominant color family
  Wallpapers/Tones/<Tone>/          generated: symlinks by overall lightness (Dark, Medium, Light)
  Wallpapers/Themes/<theme>/        generated: symlinks to the images that go with each installed theme
  README.md                         generated (unless you replaced it with your own)
  .studio-library.json              generated: the symlinks `sort` made, and the index the shell reads

Real files live only in Packs/ and Wallpapers/Topics/. Everything else is a
view of symlinks that `studio library sort` regenerates idempotently: it
removes only symlinks its own manifest lists (and only while they are still
symlinks), so files you drop into a view folder, or links you make there,
are never touched.

Images are every still in Topics/ (recursively; a subfolder is part of the
topic's name in views) plus every pack's stills: its wallpapers (a video
wallpaper through its still), its lock designs' backgrounds and previews.
Videos without a still are left out.

Color families come from the image's swatches (median cut + k-means,
palette.py, cached in <state>/cache/palettes.json): each swatch gets a
family from its hue (HSV, the hue names people use) and its CIELAB
lightness / chroma (warm hues that are dark or dull are Brown, dull reds
are Brown or dusty Pink), and counts with its share of the image times how
colorful it is. Too little color overall is Monochrome; a second family
that is at least half as strong as the first (and clearly present) puts
the image in both folders. Tones are the share-weighted CIELAB lightness.

Theme views use the vibes measure (vibes.Matcher: CIEDE2000 between the
image's swatches and the theme's wallpaper or palette, averaged with the
source pack's palette distance for pack images): the theme's own images and
its curated links always, then the closest others above a score floor.
"""

from __future__ import annotations

import colorsys
import hashlib
import json
import math
import os
import shutil
import subprocess
import time
from pathlib import Path

from . import color, palette, vibes
from .pack import Pack, media_kind

MANIFEST = ".studio-library.json"
VERSION = 1
README_MARK = "<!-- generated by `studio library sort`; delete this line to keep your own README -->"

PACKS = "Packs"
WALLPAPERS = "Wallpapers"
TOPICS = "Topics"
VIEWS = ("Colors", "Tones", "Themes")

FAMILIES = ("Red", "Orange", "Yellow", "Green", "Teal", "Blue", "Purple", "Pink", "Brown", "Monochrome")
TONES = ("Dark", "Medium", "Light")

# Bucketing (tuned on Cody's library; see the module docstring).
CHROMA_FLOOR = 5.0  # CIELAB C* below this carries no hue
CHROMA_FULL = 30.0  # … and from this on counts fully
MONO_BELOW = 0.085  # total colorfulness under this: Monochrome
SECOND_RATIO = 0.5  # a second family at least half as strong as the first …
SECOND_MIN = 0.1  # … and this strong in absolute terms
DARK_BELOW = 30.0  # share-weighted L*
LIGHT_FROM = 50.0

# Theme views.
THEME_MIN_SCORE = 0.6  # vibes score (exp(-distance / 30)): distance ≤ ~15, "same vibe"
THEME_MAX = 24  # ranked matches per theme (own and curated images come on top)

THUMB_WIDTH = 480


def root() -> Path | None:
    """The library root ($STUDIO_LIBRARY, default ~/Documents/Themes), None when turned off."""
    v = os.environ.get("STUDIO_LIBRARY", "").strip()
    if v.lower() in ("none", "off"):
        return None
    return Path(v).expanduser() if v else Path.home() / "Documents" / "Themes"


def packs_dir(lib: Path | None) -> Path | None:
    """<library>/Packs when the library exists."""
    return lib / PACKS if lib is not None and lib.is_dir() else None


# ── color buckets ───────────────────────────────────────────────────────────


def swatch_family(c: str) -> tuple[str | None, float]:
    """(family or None for a neutral, colorfulness 0..1) of one swatch."""
    lum, a, b = color.to_lab(c)
    chroma = math.hypot(a, b)
    strength = max(0.0, min(1.0, (chroma - CHROMA_FLOOR) / (CHROMA_FULL - CHROMA_FLOOR)))
    if strength <= 0:
        return None, 0.0
    # Near-black colors read as black more than as their hue.
    strength *= max(0.35, min(1.0, (lum + 5) / 25))
    r, g, bl, _ = color.parse(c)
    h = colorsys.rgb_to_hsv(r, g, bl)[0] * 360
    # Saturation in Lab terms: a dark color can still glow (embers, fire).
    sat = chroma / max(lum, 1.0)
    if h >= 345 or h < 15:
        fam = "Red" if chroma >= 30 or (chroma >= 20 and sat >= 1.2) else ("Pink" if lum >= 55 else "Brown")
    elif h < 48:
        fam = "Orange" if chroma >= 45 or sat >= 1.2 else "Brown"
    elif h < 68:
        fam = "Yellow" if chroma >= 30 and lum >= 50 else "Brown"
    elif h < 160:
        fam = "Green"
    elif h < 192:
        fam = "Teal"
    elif h < 255:
        fam = "Blue"
    elif h < 295:
        fam = "Purple"
    elif h < 325:
        fam = "Pink" if lum >= 45 else "Purple"
    else:
        fam = "Pink" if lum >= 35 or chroma < 30 else "Red"
    return fam, strength


def classify(swatches: list) -> dict:
    """{"colors": [1-2 families], "tone", "lightness", "strength": {family: 0..1}}."""
    strength: dict[str, float] = {}
    total_w = sum(w for _, w in swatches) or 1.0
    light = 0.0
    for c, w in swatches:
        light += color.to_lab(c)[0] * w / total_w
        fam, s = swatch_family(c)
        if fam:
            strength[fam] = strength.get(fam, 0.0) + s * w / total_w
    ranked = sorted(strength.items(), key=lambda t: -t[1])
    if not ranked or sum(strength.values()) < MONO_BELOW:
        colors = ["Monochrome"]
    else:
        colors = [ranked[0][0]]
        if len(ranked) > 1 and ranked[1][1] >= SECOND_MIN and ranked[1][1] >= SECOND_RATIO * ranked[0][1]:
            colors.append(ranked[1][0])
    tone = "Dark" if light < DARK_BELOW else "Light" if light >= LIGHT_FROM else "Medium"
    return {
        "colors": colors,
        "tone": tone,
        "lightness": round(light, 1),
        "strength": {k: round(v, 3) for k, v in ranked},
    }


# ── thumbnails ──────────────────────────────────────────────────────────────


def thumb_file(state_dir: Path, digest: str) -> Path:
    return Path(state_dir) / "cache" / "thumbs" / f"{digest}.jpg"


def thumb(state_dir: Path, cache: vibes.PaletteCache, path: Path, *, make: bool = True) -> str | None:
    """A ~480 px wide JPEG of the image in <state>/cache/thumbs (by content
    hash), made with ffmpeg when missing; None without ffmpeg."""
    digest = cache.digest(Path(path))
    if digest is None:
        return None
    out = thumb_file(state_dir, digest)
    if out.is_file():
        return str(out)
    if not make or not palette.have_ffmpeg():
        return None
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_name(f".{out.stem}.{os.getpid()}.jpg")
    r = subprocess.run(
        ["ffmpeg", "-nostdin", "-v", "error", "-y", "-i", str(path), "-frames:v", "1",
         "-vf", f"scale='min({THUMB_WIDTH},iw)':-2:flags=area", "-q:v", "4", str(tmp)],
        capture_output=True,
    )  # fmt: skip
    if r.returncode != 0 or not tmp.is_file() or tmp.stat().st_size == 0:
        tmp.unlink(missing_ok=True)
        return None
    os.replace(tmp, out)
    return str(out)


# ── the library ─────────────────────────────────────────────────────────────


class LibraryError(Exception):
    pass


def _is_image(p: Path) -> bool:
    return p.is_file() and not p.name.startswith(".") and media_kind(p) == "image"


class Library:
    def __init__(self, path: Path):
        self.root = Path(path).expanduser()
        self.packs = self.root / PACKS
        self.wallpapers = self.root / WALLPAPERS
        self.topics_dir = self.wallpapers / TOPICS
        self.manifest_file = self.root / MANIFEST

    def exists(self) -> bool:
        return self.root.is_dir()

    # ── images ──────────────────────────────────────────────────────────

    def topics(self) -> dict[str, list[Path]]:
        """Curated images by topic: real image files under Topics/<topic>/,
        recursively (symlinks are skipped: views and links aren't curation)."""
        out: dict[str, list[Path]] = {}
        if not self.topics_dir.is_dir():
            return out
        for d in sorted(self.topics_dir.iterdir()):
            if not d.is_dir() or d.is_symlink() or d.name.startswith("."):
                continue
            imgs = []
            for dirpath, dirnames, filenames in os.walk(d):
                dirnames[:] = sorted(n for n in dirnames if not n.startswith(".") and not (Path(dirpath) / n).is_symlink())
                for f in sorted(filenames):
                    p = Path(dirpath) / f
                    if not p.is_symlink() and _is_image(p):
                        imgs.append(p)
            out[d.name] = imgs
        return out

    def pack_dirs(self) -> list[Path]:
        if not self.packs.is_dir():
            return []
        return [d for d in sorted(self.packs.iterdir()) if (d / "theme.json").is_file()]

    def items(self) -> list[dict]:
        """Every library image: {path, source: topic|pack, topic|pack, role, label}."""
        out: list[dict] = []
        seen: set[str] = set()

        def add(path: Path, **info) -> None:
            try:
                key = str(path.resolve())
            except OSError:
                return
            if key in seen or not _is_image(path):
                return
            seen.add(key)
            out.append({"path": path, **info})

        for topic, images in self.topics().items():
            for p in images:
                sub = p.parent.relative_to(self.topics_dir / topic).parts
                add(p, source="topic", topic=topic, role="wallpaper", label=" - ".join((topic, *sub)))
        for d in self.pack_dirs():
            try:
                pack = Pack(d)
            except Exception:  # noqa: BLE001 — a broken pack never breaks the library
                continue
            for e in pack.wallpaper_entries():
                still = e["path"] if e["kind"] == "image" else e.get("preview")
                if still:
                    add(Path(still), source="pack", pack=pack.name, role="wallpaper", label=pack.name)
            for e in pack.lock_entries():
                for k in ("background", "preview"):
                    if k in e:
                        add(Path(e[k]), source="pack", pack=pack.name, role="lock", label=pack.name)
        return out

    # ── manifest ────────────────────────────────────────────────────────

    def load_manifest(self) -> dict:
        try:
            data = json.loads(self.manifest_file.read_text())
            if isinstance(data, dict) and data.get("version") == VERSION:
                return data
        except (OSError, ValueError):
            pass
        return {"version": VERSION, "links": {}}

    def _write_manifest(self, data: dict) -> None:
        tmp = self.manifest_file.with_name(f".{self.manifest_file.name}.{os.getpid()}")
        tmp.write_text(json.dumps(data, indent=1) + "\n")
        os.replace(tmp, self.manifest_file)

    # ── sort ────────────────────────────────────────────────────────────

    def sort(self, packs: dict[str, Pack], *, cache: vibes.PaletteCache, state_dir: Path | None, idx: dict | None = None) -> dict:
        """(Re)generate the views; return the index (also saved in the manifest)."""
        if not self.exists():
            raise LibraryError(f"no library at {self.root} (create it, or set STUDIO_LIBRARY)")
        items = self.items()
        images: list[dict] = []
        skipped: list[str] = []
        for it in items:
            pal = cache.get(it["path"])
            if not pal or not pal.get("swatches"):
                skipped.append(str(it["path"]))
                continue
            cls = classify(pal["swatches"])
            rec = {
                "path": str(it["path"]),
                "name": it["path"].name,
                "source": it["source"],
                "topic": it.get("topic", ""),
                "pack": it.get("pack", ""),
                "role": it["role"],
                "label": it["label"],
                **cls,
                "swatches": [c for c, _ in pal["swatches"][:5]],
            }
            if state_dir is not None:
                t = thumb(state_dir, cache, it["path"])
                if t:
                    rec["thumb"] = t
            images.append(rec)

        _short_names(images)
        themes = self._themes(images, packs, cache, idx or {})
        old = self._old = self.load_manifest().get("links", {})

        # Desired links: <view>/<bucket>/<label> - <name>.
        want: dict[str, str] = {}
        by_path = {r["path"]: r for r in images}

        def place(view: str, bucket: str, rec: dict) -> str:
            d = Path(WALLPAPERS) / view / bucket
            base = f"{rec['label']} - {rec['name']}"
            stem, ext = os.path.splitext(base)
            name, n = base, 2
            while str(d / name) in want or self._foreign(d / name, rec["path"]):
                name, n = f"{stem} ({n}){ext}", n + 1
            rel = str(d / name)
            want[rel] = rec["path"]
            return rel

        for rec in images:
            rec["links"] = [place("Colors", fam, rec) for fam in rec["colors"]]
            rec["links"].append(place("Tones", rec["tone"], rec))
        for t in themes:
            for e in t["images"]:
                e["link"] = place("Themes", t["name"], by_path[e["path"]])

        removed = created = 0
        for rel in old:
            if rel in want:
                continue
            p = self.root / rel
            if p.is_symlink():
                p.unlink()
                removed += 1
        for rel, target in want.items():
            p = self.root / rel
            dest = self._link_target(p, Path(target))
            if p.is_symlink():
                if os.readlink(p) == dest:
                    continue
                if rel not in old and Path(os.path.realpath(p)) != Path(target).resolve():
                    continue  # someone else's link (place() avoids these)
                p.unlink()
            p.parent.mkdir(parents=True, exist_ok=True)
            p.symlink_to(dest)
            created += 1
        self._prune_empty()

        index = {
            "version": VERSION,
            "root": str(self.root),
            "exists": True,
            "generated": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "images": images,
            "topics": [{"name": n, "count": sum(1 for r in images if r["topic"] == n)} for n in self.topics()],
            "packs": [{"name": n, "count": c} for n, c in _count(r["pack"] for r in images if r["source"] == "pack")],
            "colors": [{"name": f, "count": c} for f in FAMILIES if (c := sum(1 for r in images if f in r["colors"]))],
            "tones": [{"name": t, "count": c} for t in TONES if (c := sum(1 for r in images if r["tone"] == t))],
            "themes": themes,
            "skipped": skipped,
            "changes": {"created": created, "removed": removed},
        }
        self._write_manifest({"version": VERSION, "links": want, "index": index})
        self._write_readme(index)
        return index

    def _foreign(self, rel: Path, target: str) -> bool:
        """Something not ours already sits at rel (a real file, or a link elsewhere)."""
        p = self.root / rel
        if not (p.exists() or p.is_symlink()):
            return False
        if p.is_symlink():
            if str(rel) in getattr(self, "_old", {}):
                return False
            return Path(os.path.realpath(p)) != Path(target).resolve()
        return True

    def _link_target(self, link: Path, target: Path) -> str:
        """Relative inside the library (it can move or sync), else absolute."""
        try:
            target.resolve().relative_to(self.root.resolve())
            return os.path.relpath(target, link.parent)
        except ValueError:
            return str(target)

    def _prune_empty(self) -> None:
        for view in VIEWS:
            top = self.wallpapers / view
            if not top.is_dir():
                continue
            for d in sorted((p for p in top.rglob("*") if p.is_dir() and not p.is_symlink()), key=lambda p: -len(p.parts)):
                try:
                    d.rmdir()  # only when empty
                except OSError:
                    pass

    def _themes(self, images: list[dict], packs: dict[str, Pack], cache: vibes.PaletteCache, idx: dict) -> list[dict]:
        out = []
        for name in sorted(packs):
            target = packs[name]
            try:
                m = vibes.Matcher(target, packs, cache)
            except Exception:  # noqa: BLE001 — a pack without a palette has no view
                continue
            curated = {w["path"] for w in vibes.resolve(target, packs, idx)["wallpapers"]}
            own, cur, match = [], [], []
            for rec in images:
                src = rec["pack"] if rec["source"] == "pack" else ""
                d, _ = m.distance({"source_pack": src}, rec["path"])
                if d is None:
                    continue
                e = {"path": rec["path"], "distance": round(d, 2), "score": round(vibes.score(d), 3)}
                if src == name:
                    own.append(dict(e, origin="own"))
                elif rec["path"] in curated:
                    cur.append(dict(e, origin="curated"))
                elif e["score"] >= THEME_MIN_SCORE:
                    match.append(dict(e, origin="match"))
            match.sort(key=lambda e: (e["distance"], e["path"]))
            out.append(
                {
                    "name": name,
                    "polarity": m.tpol,
                    "palette": {r: m.tpal[r] for r in ("bg", "accent", "accent2") if r in m.tpal},
                    "images": own + cur + match[:THEME_MAX],
                }
            )
        return out

    # ── README ──────────────────────────────────────────────────────────

    def _write_readme(self, index: dict) -> None:
        f = self.root / "README.md"
        try:
            if f.exists() and not f.read_text(errors="replace").startswith(README_MARK):
                return
        except OSError:
            return
        f.write_text(readme(index))

    # ── add ─────────────────────────────────────────────────────────────

    def add(self, files: list[Path], topic: str, *, move: bool = False) -> list[Path]:
        if not topic or "/" in topic or topic.startswith(".") or topic in (".", ".."):
            raise LibraryError(f"invalid topic name '{topic}'")
        bad = [str(f) for f in files if not _is_image(Path(f))]
        if bad:
            raise LibraryError("not an image: " + ", ".join(bad))
        dest_dir = self.topics_dir / topic
        dest_dir.mkdir(parents=True, exist_ok=True)
        added = []
        for src in map(Path, files):
            dest = dest_dir / src.name
            n = 2
            while dest.exists():
                if _same(src, dest):
                    break
                dest = dest_dir / f"{src.stem} ({n}){src.suffix}"
                n += 1
            if dest.exists():  # already there
                if move and src.resolve() != dest.resolve():
                    src.unlink()
                continue
            if move:
                shutil.move(str(src), dest)
            else:
                shutil.copy2(src, dest)
            added.append(dest)
        return added


def _short_names(images: list[dict]) -> None:
    """`short`: a caption for pickers. Topic images drop the file-name prefix
    their topic folder shares (screencap series: "…screencaps.com-104" → "104");
    pack images are the pack's name (plus the file's when it has several)."""
    groups: dict[tuple[str, str], list[dict]] = {}
    for r in images:
        groups.setdefault((r["source"], r["label"]), []).append(r)
    for (source, label), rs in groups.items():
        stems = [os.path.splitext(r["name"])[0] for r in rs]
        if source == "pack":
            for r, stem in zip(rs, stems):
                r["short"] = label if len(rs) == 1 else f"{label} · {stem}"
            continue
        prefix = os.path.commonprefix(stems) if len(rs) > 1 else ""
        cut = max((prefix.rfind(ch) for ch in "-_ ."), default=-1) + 1 if prefix else 0
        for r, stem in zip(rs, stems):
            r["short"] = stem[cut:] or stem if len(prefix) >= 6 else stem


def _same(a: Path, b: Path) -> bool:
    if a.stat().st_size != b.stat().st_size:
        return False

    def h(p: Path) -> str:
        d = hashlib.sha1()
        with open(p, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                d.update(chunk)
        return d.hexdigest()

    return h(a) == h(b)


def _count(names) -> list[tuple[str, int]]:
    out: dict[str, int] = {}
    for n in names:
        out[n] = out.get(n, 0) + 1
    return sorted(out.items())


def load_index(lib: Library) -> dict | None:
    """The index the last `sort` saved, or None."""
    return lib.load_manifest().get("index") if lib.exists() else None


def summary(index: dict) -> str:
    lines = [f"{index['root']}  ({len(index['images'])} images)"]

    def block(title: str, rows: list[tuple[str, int]]) -> None:
        if rows:
            lines.append(f"\n{title}:")
            lines.extend(f"  {c:5}  {n}" for n, c in rows)

    block("Topics", [(t["name"], t["count"]) for t in index["topics"]])
    block("Packs", [(p["name"], p["count"]) for p in index["packs"]])
    block("Colors", [(c["name"], c["count"]) for c in index["colors"]])
    block("Tones", [(t["name"], t["count"]) for t in index["tones"]])
    block("Themes", [(t["name"], len(t["images"])) for t in index["themes"]])
    if index.get("skipped"):
        lines.append(f"\nskipped (unreadable): {len(index['skipped'])}")
    return "\n".join(lines)


def readme(index: dict) -> str:
    def counts(rows: list[dict], key: str = "count") -> str:
        return ", ".join(f"{r['name']} ({r[key] if key != 'images' else len(r['images'])})" for r in rows) or "none yet"

    return f"""{README_MARK}
# Themes

Every theme pack and wallpaper in one place, used by studio-linux (Loft).
This file and the `Colors`, `Tones` and `Themes` folders are regenerated by
`studio library sort` (last run {index['generated']}, {len(index['images'])} images).

| Folder | What | Real files? |
|---|---|---|
| `Packs/<pack>/` | Installed theme packs; `studio theme install` puts new ones here | yes |
| `Wallpapers/Topics/<Topic>/` | Your curated wallpapers, one folder per topic (subfolders are fine); `studio library add FILES --topic NAME` | yes |
| `Wallpapers/Colors/<Color>/` | Every image (topics and packs) by its dominant color | symlinks |
| `Wallpapers/Tones/<Tone>/` | Every image by overall lightness: Dark, Medium, Light | symlinks |
| `Wallpapers/Themes/<theme>/` | The images that go with each installed theme | symlinks |

Only `Packs/` and `Wallpapers/Topics/` hold files: add, rename or delete
there, then run `studio library sort` (the Wallpaper settings page does it
too). Sorting only replaces the symlinks it made itself (listed in
`.studio-library.json`); anything else you put in the generated folders is
left alone. View names are `<topic or pack> - <file name>`.

## Colors

Each image is reduced to a handful of swatches. A swatch's family comes from
its hue, its lightness and how colorful it is: warm hues that are dark or
dull are **Brown** (earth, wood, sand), dull light reds are **Pink**. A
family's strength is the swatches' share of the image times their
colorfulness. Too little color in total is **Monochrome**; when a second
family is at least half as strong as the first, the image is in both
folders (e.g. a sunset over water in Orange and Blue).

Families: Red, Orange, Yellow, Green, Teal, Blue, Purple, Pink, Brown, Monochrome.
Now: {counts(index['colors'])}.

## Tones

The image's average lightness: **Dark** suits dark themes and keeps glass
panels readable, **Light** suits light themes, **Medium** goes with either.
Combine with a color in the Wallpaper settings page (e.g. Blue + Dark).
Now: {counts(index['tones'])}.

## Themes

For every installed theme: its own wallpapers and curated links first, then
the closest other images by color (score {THEME_MIN_SCORE:g}+ on the vibes
scale, at most {THEME_MAX}). Same measure as `studio theme vibes`.
Now: {counts(index['themes'], 'images')}.

## Topics

{counts(index['topics'])}.
"""
